const fs = require('fs'), path = require('path'), vm = require('vm');
const html = fs.readFileSync(path.join(__dirname, '..', 'TRPG 작업 관리 도구.html'), 'utf8').split(String.fromCharCode(13, 10)).join(String.fromCharCode(10));
let f = 0; const ok = (c, m) => { if (!c) { f++; console.log('FAIL', m); } else console.log('ok', m); };
const ctx = {}; vm.createContext(ctx);
vm.runInContext(html.slice(html.indexOf('function ds_parseNumber'), html.indexOf('// 정렬 적용: colIds')) + ';this.f={ds_sortCompare,ds_sortPlan}', ctx);
const F = ctx.f;
const sorted = (arr, desc) => arr.slice().sort((a, b) => F.ds_sortCompare(a, b, desc));
ok(sorted(['10', '9', '2']).join() === '2,9,10', '숫자는 숫자 크기순');
ok(sorted(['나', '가', '다']).join() === '가,나,다', '한국어 사전순');
ok(sorted(['', 'b', '3', ' ', 'a']).join('|') === '3|a|b| |' || sorted(['', 'b', '3', ' ', 'a']).slice(0, 3).join() === '3,a,b', '숫자 < 글자, 빈 칸은 뒤');
ok(sorted(['', 'b', '3', 'a'], true).join() === 'b,a,3,', '내림차순에서도 빈 칸은 맨 뒤');
ok(sorted(['a2', 'a10', 'a1']).join() === 'a1,a2,a10', '글자 속 숫자 자연 정렬(numeric)');
const row = v => ({ cells: { a: v } });
let rows = [row('c'), row('a'), row('b')];
ok(F.ds_sortPlan(rows, [{ colId: 'a', desc: false }], 0, 2).join() === '1,2,0', '정렬 계획(순서)');
ok(F.ds_sortPlan(rows, [{ colId: 'a', desc: false }], 1, 2).join() === '0,1,2', '범위 시작 이후만(고정 행·머리글 제외)');
rows = [row('b'), row('a'), { isCategory: true }, row('z'), { isMemo: true }, row('y')];
ok(F.ds_sortPlan(rows, [{ colId: 'a', desc: false }], 0, 5).join() === '1,0,2,5,4,3', '카테고리 구간별 정렬, 카테고리·메모 행 자리 유지');
rows = [{ cells: { a: '1', b: 'y' } }, { cells: { a: '1', b: 'x' } }, { cells: { a: '0', b: 'z' } }];
ok(F.ds_sortPlan(rows, [{ colId: 'a' }, { colId: 'b' }], 0, 2).join() === '2,1,0', '다중 기준(두 번째 열)');
ok(F.ds_sortPlan([row('1'), row('1')], [{ colId: 'a' }], 0, 1).join() === '0,1', '안정 정렬(같으면 옛 순서)');
ok(/시트 정렬 A→Z/.test(html) && /시트 정렬 Z→A/.test(html) && /범위 정렬…/.test(html) && /id="ds-sort-submit">실행<\/button>\s*<button[^>]*id="ds-sort-cancel">취소/.test(html), '메뉴·대화상자(버튼 순서 [실행][취소])');
ok(sorted(['1,000', '+5', '20']).join() === '+5,20,1,000'.replace('1,000', '1,000') || sorted(['1,000', '+5', '20']).join('|') === '+5|20|1,000', '숫자 인식: 1,000 · +5 도 숫자 크기순');
process.exit(f ? 1 : 0);
