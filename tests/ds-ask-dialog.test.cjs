const fs = require('fs'), path = require('path'), vm = require('vm');
const html = fs.readFileSync(path.join(__dirname, '..', 'TRPG 작업 관리 도구.html'), 'utf8').split(String.fromCharCode(13, 10)).join(String.fromCharCode(10));
let f = 0; const ok = (c, m) => { if (!c) { f++; console.log('FAIL', m); } else console.log('ok', m); };
const els = {}, open = [];
const el = id => els[id] || (els[id] = { id, value: '', textContent: '', disabled: false, attrs: {}, setAttribute(n, v) { this.attrs[n] = v; }, removeAttribute(n) { delete this.attrs[n]; }, focus() {}, select() {} });
const ctx = { document: { getElementById: el }, ds_dialogShow: id => open.push(id), ds_dialogHide: () => open.pop() };
vm.createContext(ctx);
vm.runInContext(html.slice(html.indexOf('function ds_ask('), html.indexOf('function ds_saveStyleRules')), ctx);
const got = [];
const key = (k, extra) => el('ds-ask-dialog').onkeydown({ key: k, target: el('ds-ask-input'), preventDefault() {}, stopPropagation() {}, ...extra });
ctx.ds_ask({ title: '각도', type: 'number', value: '30', attrs: { min: -90, max: 90 }, check: v => Math.abs(Number(v)) <= 90 && v ? '' : '범위' }, v => got.push(v));
ok(el('ds-ask-input').type === 'number' && el('ds-ask-input').attrs.max === 90 && open.length === 1, '숫자 입력창 열기');
el('ds-ask-input').value = '120'; key('Enter');
ok(!got.length && open.length === 1 && el('ds-ask-error').textContent === '범위', '범위 밖: 오류 표시, 닫지 않음');
key('Enter', { isComposing: true }); el('ds-ask-input').value = '-45'; el('ds-ask-input').oninput(); key('Enter', { isComposing: true });
ok(!got.length, '한글 조합 중 Enter 무시');
key('Enter');
ok(got.join() === '-45' && !open.length, 'Enter 확인');
ctx.ds_ask({ title: '이름', value: '보기', attrs: { maxlength: 60 }, required: true }, v => got.push(v));
ok(el('ds-ask-input').attrs.maxlength === 60 && !('max' in el('ds-ask-input').attrs) && !el('ds-ask-ok').disabled, '이전 속성 지움');
el('ds-ask-input').value = '  '; el('ds-ask-input').oninput(); key('Enter');
ok(el('ds-ask-ok').disabled && got.length === 1 && open.length === 1, '빈 이름: 확인 비활성');
key('Escape');
ok(!open.length && got.length === 1, 'Esc 취소');
ok(!/prompt\('(필터 보기 이름|회전 각도)/.test(html), 'prompt 제거');
process.exit(f ? 1 : 0);
