const fs = require('fs'), path = require('path'), vm = require('vm');
const html = fs.readFileSync(path.join(__dirname, '..', 'TRPG 작업 관리 도구.html'), 'utf8').split(String.fromCharCode(13, 10)).join(String.fromCharCode(10));
let f = 0; const ok = (c, m) => { if (!c) { f++; console.log('FAIL', m); } else console.log('ok', m); };
const ctx = {}; vm.createContext(ctx);
vm.runInContext(html.slice(html.indexOf('function musicSidebarGroups'), html.indexOf('const musicSidebarClosed')), ctx);
const folders = [{ id: 'f2', name: '전투', color: '#f00' }, { id: 'f1', name: '일상', color: '#0f0' }, { id: 'f3', name: '빈 폴더', color: '#00f' }];
const tracks = [{ id: 'a', folderId: 'f1' }, { id: 'b', folderId: '' }, { id: 'c', folderId: 'f2' }, { id: 'd', folderId: 'f1' }, { id: 'e', folderId: 'gone' }];
const g = ctx.musicSidebarGroups(tracks, folders);
const shape = g.map(x => x.id + ':' + x.tracks.map(t => t.id).join('')).join(' ');
ok(shape === 'f2:c f1:ad none:be', '폴더 순서·빈 폴더 숨김·분류 없음 맨 아래(없는 폴더 포함)·곡 순서 유지');
ok(ctx.musicSidebarGroups([], folders).length === 0, '곡이 없으면 묶음 없음');
const side = html.slice(html.indexOf('function renderMusicSidebar'), html.indexOf('function musicVisibleTracks'));
ok(/musicVisibleTracks\(\)/.test(side) && !/innerHTML/.test(side), '그리드와 같은 결과 사용·제목은 textContent');
const page = html.slice(html.indexOf('function renderMusicPage'), html.indexOf('async function musicShowStorage'));
ok(/currentPage === 'music'\) renderList\(\)/.test(page), '검색·정렬·변경 때 왼쪽 목록도 다시 그림');
const create = html.slice(html.indexOf("function createNew(folderId = '')"), html.indexOf('function delScenario'));
ok(/currentPage === 'music'\) \{\s*openMusicYoutubeModal\(\);\s*return;/.test(create) && /function createFolder\(\) \{\s*if \(currentPage === 'music'\) \{ openMusicFolderModal\(\); return; \}/.test(html), '＋ 곡·＋ 폴더는 음악용 창(시나리오 생성 안 함)');
ok(/btn\.textContent = '＋ 곡'/.test(html) && /id="music-folders"/.test(html), '버튼 이름·페이지 안 폴더 패널 유지');
process.exit(f ? 1 : 0);
