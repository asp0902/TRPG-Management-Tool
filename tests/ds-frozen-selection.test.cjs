const fs = require('fs'), path = require('path'), vm = require('vm');
const html = fs.readFileSync(path.join(__dirname, '..', 'TRPG 작업 관리 도구.html'), 'utf8').split(String.fromCharCode(13, 10)).join(String.fromCharCode(10));
let f = 0; const ok = (c, m) => { if (!c) { f++; console.log('FAIL', m); } else console.log('ok', m); };
const ctx = {}; vm.createContext(ctx);
vm.runInContext(html.slice(html.indexOf('function ds_frozenClip'), html.indexOf('// 선택 모양(#383')), ctx);
const rect = o => ({ getBoundingClientRect: () => o });
const td = (...cls) => ({ classList: { contains: c => cls.includes(c) } });
const body = map => ({ querySelector: () => ({ querySelector: s => map[s] || null }) });
const frozen = body({ 'tbody td.ds-frozen-row-last': rect({ bottom: 200 }), 'thead th.ds-frozen-col-last': rect({ right: 300 }), 'thead th.ds-select-all-corner': rect({ bottom: 100, right: 50 }) });
const C = (r, a, b, bd = frozen) => ctx.ds_frozenClip(bd, r, a, b);
const R = { left: 320, top: 150, right: 500, bottom: 260 };
ok(C(R, td(), td()).clip === 'inset(50px 0 0 0px)', '고정 행 아래로 가림');
ok(C({ ...R, top: 210 }, td(), td()).clip === '', '안 겹치면 그대로');
ok(C({ ...R, left: 250, top: 210 }, td(), td()).clip === 'inset(0px 0 0 50px)', '고정 열 아래로 가림');
const span = C({ left: 320, top: 120, right: 500, bottom: 180 }, td('ds-frozen-row'), td());
ok(span.clip === '' && span.bottom === 200, '걸친 선택: 고정 부분 유지');
ok(C({ left: 320, top: 120, right: 500, bottom: 180 }, td('ds-frozen-row'), td('ds-frozen-row')).bottom === 180, '고정 칸만: 그대로');
const plain = body({ 'thead th.ds-select-all-corner': rect({ bottom: 100, right: 50 }) });
ok(C({ left: 30, top: 80, right: 200, bottom: 160 }, td(), td(), plain).clip === 'inset(20px 0 0 20px)', '고정이 없어도 머리글·행 번호 아래로');
ok((html.match(/ds_frozenClip\(body/g) || []).length >= 4, '범위·활성 칸·채우기 핸들·미리보기 연결');
process.exit(f ? 1 : 0);
