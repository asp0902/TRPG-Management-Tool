const fs = require('fs'), path = require('path'), vm = require('vm');
const html = fs.readFileSync(path.join(__dirname, '..', 'TRPG 작업 관리 도구.html'), 'utf8').split(String.fromCharCode(13,10)).join(String.fromCharCode(10));
let fails = 0; const ok = (c, m) => { if (!c) { fails++; console.log('FAIL', m); } else console.log('ok', m); };
const cut = (a, b) => html.slice(html.indexOf(a), html.indexOf(b));
const code = cut('function normalizeCharacterEntry', 'function compareCharactersByName') + cut('// 페어 양방향 반영', 'function compareCharactersByName');
const ctx = { state: { characters: [] }, mkId: () => 'new', normalizeCharacterSheets: () => [], normalizeCharacterColor: c => c, normalizeCharacterTokenSize: n => n };
vm.createContext(ctx); vm.runInContext(code + ';this.f={normalizeCharacterEntry,applyCharacterPairs,removeCharacterFromPairs}', ctx);
const f = ctx.f, S = ctx.state;
ok(JSON.stringify(f.normalizeCharacterEntry({ id: 'a' }).pairIds) === '[]', '구 데이터(pairIds 없음) → []');
ok(JSON.stringify(f.normalizeCharacterEntry({ id: 'a', pairIds: ['a', 'b', 'b', '', 3] }).pairIds) === '["b"]', '자기 자신·중복·비문자열 제거');
S.characters = [{ id: 'a' }, { id: 'b' }, { id: 'c' }];
f.applyCharacterPairs('a', ['b', 'c', 'a']);
const g = id => (S.characters.find(c => c.id === id).pairIds || []);
ok(g('a').join() === 'b,c' && g('b').join() === 'a' && g('c').join() === 'a', '양방향 추가(자기 자신 제외)');
f.applyCharacterPairs('a', ['c']);
ok(g('a').join() === 'c' && g('b').length === 0 && g('c').join() === 'a', '해제 시 양쪽에서 제거');
f.applyCharacterPairs('b', ['c']);
ok(g('c').join() === 'a,b' && g('b').join() === 'c', '기존 페어 유지하며 추가');
S.characters = S.characters.filter(c => c.id !== 'c'); f.removeCharacterFromPairs('c');
ok(g('a').length === 0 && g('b').length === 0, '삭제 시 남은 캐릭터에서 id 제거');
ok(/function deleteCharacter\(\) \{[\s\S]*?removeCharacterFromPairs\(deletedId\)/.test(html) && /function deleteCharacterById\(id\) \{[\s\S]*?removeCharacterFromPairs\(id\)/.test(html), '두 삭제 함수에서 정리 호출');
ok(html.includes('applyCharacterPairs(ch.id, _chPairs)') && html.includes('applyCharacterPairs(newCh.id, _chPairs)'), '저장 시 양방향 반영(편집·신규)');
ok(html.includes('character-card-pair" title="페어" onclick="openCharacterModal('), '카드 페어 칩 클릭 → 편집 모달');
ok(html.includes('id="ch-modal-pairs"') && html.includes('id="ch-pair-select"'), '모달 페어 칩·선택 칸');
console.log('fails=' + fails); process.exit(fails ? 1 : 0);
